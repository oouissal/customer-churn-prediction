"""FastAPI application entry point.

Run locally with::

    uvicorn app.main:app --reload --port 8000

Interactive documentation is auto-generated by OpenAPI at ``/docs`` and
``/redoc``.
"""

from __future__ import annotations

import logging

from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from app.api.routes import dashboard, health, model, prediction
from app.core.config import API_PREFIX, APP_NAME, APP_VERSION, CORS_ORIGINS, LOG_LEVEL

logging.basicConfig(
    level=getattr(logging, LOG_LEVEL.upper(), logging.INFO),
    format="%(asctime)s | %(levelname)-8s | %(name)s | %(message)s",
)

app = FastAPI(
    title=APP_NAME,
    version=APP_VERSION,
    description=(
        "REST API serving the customer churn prediction model: single and "
        "batch scoring, SHAP explanations, model metadata and dashboard "
        "statistics."
    ),
    docs_url="/docs",
    redoc_url="/redoc",
    openapi_url=f"{API_PREFIX}/openapi.json",
)

# CORS: the React dev server (Vite) and the dockerised frontend origins.
app.add_middleware(
    CORSMiddleware,
    allow_origins=CORS_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)

# ---------------------------------------------------------------------------
# Routers
# ---------------------------------------------------------------------------
app.include_router(health.router, prefix=API_PREFIX)
app.include_router(model.router, prefix=API_PREFIX)
app.include_router(prediction.router, prefix=API_PREFIX)
app.include_router(dashboard.router, prefix=API_PREFIX)


# ---------------------------------------------------------------------------
# Error handling
# ---------------------------------------------------------------------------
@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Log unexpected errors and return a clean 500 payload."""
    logging.getLogger("app").exception("Unhandled error on %s", request.url.path)
    return JSONResponse(
        status_code=500,
        content={"detail": "Internal server error."},
    )


@app.get(f"{API_PREFIX}/", include_in_schema=False)
def root() -> dict:
    """Convenience root pointing to the documentation."""
    return {
        "app": APP_NAME,
        "version": APP_VERSION,
        "docs": "/docs",
    }
